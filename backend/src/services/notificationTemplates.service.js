import { config } from '../config/env.js';

/**
 * Strips sensitive tokens, cookies, or secrets from any text content.
 */
export function sanitizeText(text) {
  if (!text || typeof text !== 'string') return '';
  return text
    .replace(/(bearer\s+)[a-zA-Z0-9_\-\.]{15,}/gi, '$1[REDACTED]')
    .replace(/(password\s*[:=]\s*)[^\s,]+/gi, '$1[REDACTED]')
    .replace(/(key\s*[:=]\s*)[^\s,]+/gi, '$1[REDACTED]')
    .replace(/(secret\s*[:=]\s*)[^\s,]+/gi, '$1[REDACTED]');
}

/**
 * Builds formatted Slack webhook payload conforming to Slack Block Kit standards.
 */
export function buildSlackPayload({ incident, eventType, topCandidate = null, context = {} }) {
  const incId = incident?.id || 'INC-UNKNOWN';
  const title = sanitizeText(incident?.title || 'Operational Incident');
  const severity = incident?.severity || 'SEV-2';
  const status = (incident?.status || 'investigating').toUpperCase();
  const service = incident?.serviceName || incident?.serviceId || 'Core Infrastructure';
  const lead = incident?.lead || 'Unassigned';
  const incidentUrl = `${config.appBaseUrl}/incidents/${incId}`;

  const severityEmoji = severity === 'SEV-1' ? '🔥' : severity === 'SEV-2' ? '⚠️' : 'ℹ️';

  const blocks = [
    {
      type: 'header',
      text: {
        type: 'plain_text',
        text: `${severityEmoji} [${severity}] ${title.substring(0, 140)}`,
        emoji: true
      }
    },
    {
      type: 'section',
      fields: [
        { type: 'mrkdwn', text: `*Incident ID:*\n\`${incId}\`` },
        { type: 'mrkdwn', text: `*Status:*\n*${status}*` },
        { type: 'mrkdwn', text: `*Affected Service:*\n${service}` },
        { type: 'mrkdwn', text: `*Incident Commander:*\n${lead}` }
      ]
    }
  ];

  // Optional RCA diagnosis hypothesis
  if (topCandidate && topCandidate.candidateServiceId) {
    const confidencePct = Math.round((topCandidate.score || topCandidate.confidenceScore || 0.85) * 100);
    blocks.push({
      type: 'section',
      text: {
        type: 'mrkdwn',
        text: `🔍 *AI Diagnostic Hypothesis (RCA Engine)*:\nSuspected Root Cause: *${topCandidate.candidateServiceId}* (${confidencePct}% confidence score)\n_⚠️ Hypothesis generated by topological correlation; pending responder verification._`
      }
    });
  }

  // Action link button to incident war room
  blocks.push({
    type: 'actions',
    elements: [
      {
        type: 'button',
        text: {
          type: 'plain_text',
          text: 'Open Incident War Room →',
          emoji: true
        },
        url: incidentUrl,
        style: severity === 'SEV-1' ? 'danger' : 'primary'
      }
    ]
  });

  return {
    text: `${severityEmoji} [${severity}] ${title} (${incId}) - ${status}`,
    blocks
  };
}

